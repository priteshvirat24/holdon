/**
 * Run HoldOn's real risk engine (rules + Mistral judge) on 20 labelled purchases.
 *   npm run eval
 * Writes evals/results.json (shown on the dashboard) and evals/SCORECARD.md.
 */
import fs from "node:fs";
import { assess, type MerchantRow } from "../lib/risk/assess";
import { CASES } from "../evals/cases";

const POLICY = { per_item_limit_cents: 15000, auto_capture_max_cents: 6000, hold_timeout_hours: 24, blocked_categories: ["gift_cards", "crypto"] };

async function main() {
  const rows: any[] = [];
  for (const c of CASES) {
    const merchant = {
      id: `eval_${c.domain}`,
      domain: c.domain,
      display_name: c.shop,
      registered_at: new Date(Date.now() - c.ageDays * 86_400_000).toISOString(),
      registered_source: "demo-seed",
      allowlisted: !!c.allowlisted,
    } as MerchantRow;
    const t = Date.now();
    const a = await assess({
      familyId: "fam_eval",
      purchaseId: `eval_${c.id}`,
      parentName: "Sunita",
      approverName: "Priya",
      item: c.item,
      category: c.category,
      amountCents: c.priceCents,
      merchant,
      marketQuery: c.item,
      marketSeedCents: c.marketCents,
      pageText: `${c.shop}\n${c.item}\n$${(c.priceCents / 100).toFixed(2)}\n${c.page}`,
      policy: POLICY,
      now: new Date(),
    });
    const ok = a.risk.decision === c.expect;
    rows.push({
      id: c.id, label: c.label, shop: c.shop, item: c.item, price: c.priceCents, expect: c.expect, got: a.risk.decision, ok,
      score: a.risk.score, injectionExpected: !!c.injection, injectionDetected: a.judge.injection_detected,
      reasons: a.risk.lines.filter((l: any) => l.points > 0).map((l: any) => l.label), model: a.judge.model, ms: Date.now() - t, why: c.why,
    });
    console.log(`${ok ? "✓" : "✗"} ${c.id} ${c.label.padEnd(5)} expect ${c.expect.padEnd(12)} got ${a.risk.decision.padEnd(12)} score ${String(a.risk.score).padStart(3)}  ${a.judge.model} ${Date.now() - t}ms  ${c.shop}`);
  }

  const scams = rows.filter((r) => r.label === "scam");
  const legit = rows.filter((r) => r.label === "legit");
  const legitAuto = legit.filter((r) => r.expect === "AUTO_APPROVE");
  const inj = rows.filter((r) => r.injectionExpected);
  const summary = {
    ranAt: new Date().toISOString(),
    cases: rows.length,
    accuracy: rows.filter((r) => r.ok).length,
    scamsCaught: scams.filter((r) => r.got !== "AUTO_APPROVE").length,
    scams: scams.length,
    falseAlarms: legitAuto.filter((r) => r.got !== "AUTO_APPROVE").length,
    legitAuto: legitAuto.length,
    injectionsCaught: inj.filter((r) => r.injectionDetected).length,
    injections: inj.length,
    injectionFalsePositives: rows.filter((r) => !r.injectionExpected && r.injectionDetected).length,
    medianMs: rows.map((r) => r.ms).sort((a, b) => a - b)[Math.floor(rows.length / 2)],
  };
  fs.writeFileSync("evals/results.json", JSON.stringify({ summary, rows }, null, 2) + "\n");
  const md = [
    "# HoldOn risk engine scorecard",
    "",
    `Run ${summary.ranAt.slice(0, 16).replace("T", " ")} UTC on ${summary.cases} labelled purchases (all shops fictional). Generated by \`npm run eval\`.`,
    "",
    "| Metric | Result |",
    "|---|---|",
    `| Decisions matching the label | **${summary.accuracy}/${summary.cases}** |`,
    `| Scams stopped (held or blocked) | **${summary.scamsCaught}/${summary.scams}** |`,
    `| Legit everyday purchases wrongly held | **${summary.falseAlarms}/${summary.legitAuto}** |`,
    `| Hidden AI-agent instructions detected | **${summary.injectionsCaught}/${summary.injections}** (false positives: ${summary.injectionFalsePositives}) |`,
    `| Median time per check | ${(summary.medianMs / 1000).toFixed(1)} s |`,
    "",
    "| # | Type | Shop · item | Expected | Got | Score | Why it's in the set |",
    "|---|---|---|---|---|---|---|",
    ...rows.map((r) => `| ${r.id} | ${r.label} | ${r.shop} · ${r.item} ($${(r.price / 100).toFixed(2)}) | ${r.expect} | ${r.ok ? "✅" : "❌"} ${r.got} | ${r.score} | ${r.why} |`),
    "",
  ].join("\n");
  fs.writeFileSync("evals/SCORECARD.md", md);
  console.log("\n", summary);
  process.exit(0);
}
main().catch((e) => {
  console.error(e);
  process.exit(1);
});
